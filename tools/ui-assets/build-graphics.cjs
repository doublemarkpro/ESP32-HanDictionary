// Reproducible exports from checked-in raster originals and original vector art.
// Only writes this generator's owned graphics directories; no firmware integration.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const {vectorAssets} = require('./graphics-vectors.cjs');
const root = path.resolve(__dirname, '../..');
const dest = path.join(root, 'content/sdcard/handict/ui/graphics');
const source = path.join(root, 'assets/graphics');
const previews = path.join(root, 'docs/ui/graphics');
const relative = file => path.relative(root, file).replaceAll('\\', '/');
const sha256 = data => crypto.createHash('sha256').update(data).digest('hex');
function write(file, data) {
  fs.mkdirSync(path.dirname(file), {recursive:true});
  fs.writeFileSync(file, data);
}
function weatherAssetId(condition) {
  const id = `weather-${condition}`;
  return vectorAssets().some(a => a.id === id && a.group === 'weather') ? id : 'weather-unknown';
}
async function build() {
  const all = vectorAssets();
  const prompts = JSON.parse(fs.readFileSync(path.join(source, 'prompts.json')));
  for (const job of prompts.assets) {
    const file = path.join(source, 'source/raster', job.source);
    const m = await sharp(file).metadata();
    const stats = await sharp(file).stats();
    if (!m.hasAlpha || stats.channels[3].min !== 0) throw Error(`Transparent cutout required: ${job.id}`);
    all.push({id:job.id, group:job.id.startsWith('home-')?'home':'illustration',
      width:m.width, height:m.height, file, sizes:job.id.startsWith('home-')?[192,256,384]:[320,480,640]});
  }
  const entries = [];
  for (const asset of all) {
    const isVector = !!asset.svg;
    const file = isVector ? path.join(source, 'source/vector', asset.id+'.svg') : asset.file;
    if (isVector) write(file, asset.svg+'\n');
    const original = fs.readFileSync(file);
    const entry = {id:asset.id, group:asset.group, source:relative(file),
      origin:isVector?'original-vector':'ai-generated-illustration', source_sha256:sha256(original),
      source_hash_encoding:isVector?'UTF-8 with LF line endings':'binary',
      opaque:!!asset.opaque, variants:[]};
    for (const width of asset.sizes) {
      const height = Math.round(width*asset.height/asset.width);
      const output = path.join(dest, asset.id, `${width}.png`);
      const png = await sharp(original).resize(width,height,{fit:'contain',background:'#00000000'})
        .ensureAlpha().png({compressionLevel:9}).toBuffer();
      write(output,png);
      entry.variants.push({width,height,path:path.relative(dest,output).replaceAll('\\','/'),
        bytes:png.length,decoded_rgba_bytes:width*height*4,sha256:sha256(png)});
    }
    entries.push(entry);
  }
  const small = entries.filter(e=>['control','weather'].includes(e.group));
  let c = '// Generated by tools/ui-assets/build-graphics.cjs. Do not hand edit.\n#include "han_graphics_small.h"\n#include <string.h>\n';
  let total = 0;
  for (const entry of small) {
    const v = entry.variants.find(v=>v.width===(entry.group==='control'?48:96));
    const bytes = fs.readFileSync(path.join(dest,v.path)); total += bytes.length;
    const name = entry.id.replaceAll('-','_');
    c += `static const uint8_t ${name}_png[] = {\n`;
    for(let i=0;i<bytes.length;i+=16) c+='    '+Array.from(bytes.subarray(i,i+16),b=>'0x'+b.toString(16).padStart(2,'0')).join(', ')+',\n';
    c += `};\nstatic const lv_image_dsc_t ${name} = {\n    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RAW_ALPHA, .w = ${v.width}, .h = ${v.height}},\n    .data_size = sizeof(${name}_png), .data = ${name}_png,\n};\n`;
  }
  c+='static const han_graphic_entry_t entries[] = {\n'+small.map(e=>`    {"${e.id}", &${e.id.replaceAll('-','_')}},`).join('\n')+'\n};\n';
  c+='size_t han_graphics_count(void) { return sizeof(entries) / sizeof(entries[0]); }\n';
  c+='const han_graphic_entry_t *han_graphics_at(size_t i) { return i < han_graphics_count() ? &entries[i] : NULL; }\n';
  c+='const lv_image_dsc_t *han_graphics_find(const char *id) {\n    if (!id) return NULL;\n    for (size_t i = 0; i < han_graphics_count(); ++i) {\n        if (strcmp(id, entries[i].id) == 0) return entries[i].image;\n    }\n    return NULL;\n}\n';
  write(path.join(source,'lvgl/han_graphics_small.c'),c);
  const manifest = {schema_version:1,theme:'cream-pastel-v1',lvgl_major:9,
    png_format:'RGBA8, straight alpha, lossless',path_base:'handict/ui/graphics',
    default_storage:'SD; not linked into firmware',weather_fallback:'weather-unknown',
    small_c_pack:{weather_size:96,control_size:48,count:small.length,png_bytes:total},
    totals:{assets:entries.length,pngs:entries.reduce((n,e)=>n+e.variants.length,0),
      png_bytes:entries.reduce((n,e)=>n+e.variants.reduce((s,v)=>s+v.bytes,0),0)},assets:entries};
  write(path.join(dest,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  await sheets(entries);
  console.log(JSON.stringify({totals:manifest.totals,small_c_pack:manifest.small_c_pack},null,2));
  return manifest;
}
async function sheets(entries) {
  const opentype = require(require.resolve('opentype.js',{paths:[path.dirname(require.resolve('lv_font_conv/package.json'))]}));
  const font=opentype.loadSync(path.join(root,'managed_components/lvgl__lvgl/scripts/built_in_font/SourceHanSansSC-Normal.otf'));
  function label(text,x,y,size=20,color='#142b57') {
    const p=font.getPath(text,x,y,size); p.fill=color; return p.toSVG();
  }
  const svg=(w,h,body)=>Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}">${body}</svg>`);
  async function sheet(name,items,cols,cw,ch,iw,title) {
    const w=cols*cw+48,h=Math.ceil(items.length/cols)*ch+112;
    let body=`<rect width="${w}" height="${h}" fill="#fff9f0"/>`+label(title,24,43,27);
    const overlays=[];
    for(const [i,e] of items.entries()) {
      const x=24+i%cols*cw,y=78+Math.floor(i/cols)*ch;
      body+=`<rect x="${x+4}" y="${y}" width="${cw-8}" height="${ch-10}" rx="18" fill="#ffffff"/>`;
      body+=label(e.id,x+14,y+ch-27,Math.min(15,(cw-26)/e.id.length*1.8));
      const v=e.variants.at(-1);
      overlays.push({input:await sharp(path.join(dest,v.path)).resize(iw,ch-65,{fit:'inside'}).png().toBuffer(),
        left:x+Math.round((cw-iw)/2),top:y+10});
    }
    write(path.join(previews,name+'.png'),await sharp(svg(w,h,body)).composite(overlays).png().toBuffer());
  }
  await sheet('illustrations',entries.filter(e=>['home','illustration'].includes(e.group)),3,320,290,260,'首页与学习插画 · 透明素材');
  await sheet('weather',entries.filter(e=>e.group==='weather'),6,194,207,150,'天气图标 · 22 种状态');
  await sheet('controls',entries.filter(e=>e.group==='control'),7,170,129,56,'操作与设备状态 · 统一线条图标');
  await sheet('backgrounds',entries.filter(e=>['panel','background','decor'].includes(e.group)),3,320,235,270,'背景、卡片与角落装饰');
  // Asset composition only: not a screenshot from running firmware.
  const homes=['home-book','home-headphones','home-calendar','home-timer','home-alarm','home-weather'];
  const titles=['查字典','英语音标','课程表','作业计时','小闹钟','看天气'];
  const hints=['这个字怎么写？','听一听 · 读一读','今天上什么课','每一份认真都算数','按时开始好习惯','出门前看一看'];
  const colors=['mint','lavender','sky','peach','rose','sunrise'];
  let body='<rect width="1280" height="720" fill="#fff9f0"/>'+label('我的学习小伙伴',40,66,38)+label('今天，也有许多新发现',42,103,22,'#77859b');
  const layers=[];
  for(let i=0;i<6;i++) {
    const x=30+i%3*414,y=142+Math.floor(i/3)*257;
    const panel=entries.find(e=>e.id==='panel-'+colors[i]);
    layers.push({input:path.join(dest,panel.variants[0].path),left:x,top:y});
    const art=entries.find(e=>e.id===homes[i]);
    layers.push({input:await sharp(path.join(dest,art.variants.at(-1).path)).resize(192,175,{fit:'contain',background:'#00000000'}).png().toBuffer(),left:x+192,top:y+22});
  }
  let textLayer='';
  for(let i=0;i<6;i++) {
    const x=54+i%3*414,y=142+Math.floor(i/3)*257;
    textLayer+=label(titles[i],x,y+80,32)+label(hints[i],x,y+117,18,'#5f7891');
  }
  textLayer+=label('素材排版预览 · 非真机截图 · 文字由界面动态绘制',40,684,18,'#8c9b9a');
  layers.push({input:svg(1280,720,textLayer),left:0,top:0});
  write(path.join(previews,'home-composition.png'),await sharp(svg(1280,720,body)).composite(layers).png().toBuffer());
}
if(require.main===module) build().catch(e=>{console.error(e);process.exitCode=1;});
module.exports={build,weatherAssetId};
